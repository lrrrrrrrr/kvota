#!/usr/bin/env python3
"""Regenerate KvotaKit/Sources/KvotaCore/Pricing/PricingTable.swift from LiteLLM's
public price list (https://github.com/BerriAI/litellm).

Usage:
    python3 scripts/update-pricing.py            # downloads the latest list
    python3 scripts/update-pricing.py prices.json  # uses a local copy

Only models used by Claude Code, Codex CLI and Gemini CLI are kept, so the table
stays small. Prices are stored as USD per token.
"""
import json
import pathlib
import re
import sys
import urllib.request

SOURCE = "https://raw.githubusercontent.com/BerriAI/litellm/main/model_prices_and_context_window.json"
OUT = pathlib.Path(__file__).resolve().parent.parent / "KvotaKit/Sources/KvotaCore/Pricing/PricingTable.swift"

KEEP = re.compile(
    r"^(claude-(opus|sonnet|haiku|fable|mythos)[a-z0-9.\-]*"
    r"|gpt-5[a-z0-9.\-]*|o3[a-z0-9.\-]*|o4-mini[a-z0-9.\-]*|codex-mini[a-z0-9.\-]*"
    r"|gemini-(2\.5|3)[a-z0-9.\-]*)$"
)
SKIP = re.compile(r"(image|tts|audio|live|embedding|realtime|search|transcribe|computer-use|-v\d+:\d+$)")


def load(argv):
    if len(argv) > 1:
        return json.loads(pathlib.Path(argv[1]).read_text())
    with urllib.request.urlopen(SOURCE, timeout=60) as resp:
        return json.loads(resp.read())


def main(argv):
    data = load(argv)
    rows = {}
    for key, value in data.items():
        if not isinstance(value, dict):
            continue
        name = key.split("/")[-1] if key.startswith(("gemini/", "anthropic/", "openai/")) else key
        if "/" in name or not KEEP.match(name) or SKIP.search(name):
            continue
        inp = value.get("input_cost_per_token")
        out = value.get("output_cost_per_token")
        if not inp or not out:
            continue
        cread = value.get("cache_read_input_token_cost") or 0.0
        cwrite = value.get("cache_creation_input_token_cost") or 0.0
        # Prefer the bare key over provider-prefixed duplicates.
        if name in rows and "/" in key:
            continue
        rows[name] = (inp, out, cread, cwrite)

    lines = [
        "// Generated by scripts/update-pricing.py from LiteLLM's public price list.",
        "// Do not edit by hand; rerun the script instead.",
        "",
        "extension Pricing {",
        "    /// USD per token: input, output, cache read, cache write.",
        "    static let table: [String: ModelPrice] = [",
    ]
    for name in sorted(rows):
        inp, out, cread, cwrite = rows[name]
        lines.append(
            f'        "{name}": ModelPrice(input: {inp!r}, output: {out!r}, cacheRead: {float(cread)!r}, cacheWrite: {float(cwrite)!r}),'
        )
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {len(rows)} models to {OUT}")


if __name__ == "__main__":
    main(sys.argv)
